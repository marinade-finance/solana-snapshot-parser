#[derive(Parser, Debug)]
#[command(author, version, about, long_about = None)]
struct Args {
    /// Path to the directory where the snapshot is unpacked (e.g., from .tar.zst)
    #[arg(long, env, value_parser = path_parser)]
    ledger_path: PathBuf,

    /// Path to SQLite DB data to write to (e.g., snapshot.db)
    #[arg(long, env)]
    output_sqlite: String,

    /// Path to write the slot of the loaded bank to (e.g., slot.txt)
    #[arg(long, env)]
    output_slot: Option<String>,

    /// Path to filters file generated by solana-snapshot-manager CLI
    #[arg(long, env, value_parser = path_parser)]
    filters: PathBuf,

    /// Tokio Sender/receiver channel size for communication
    #[arg(long)]
    channel_size: Option<usize>,

    /// SQLite3 cache size in MB
    #[arg(long)]
    sqlite_cache_size: Option<i64>,

    // SQLite3 memory mapped IO file size in MB, 0 means to disable
    #[arg(long)]
    sqlite_mmap_size: Option<u64>,

    /// Processing in transaction bulks. This is number of inserts in one transaction.
    #[arg(long)]
    sqlite_tx_bulk: Option<u16>,

    /// Cross-check the single-pass account scan against the accounts index; costs a scan per owner
    #[arg(long, env, default_value_t = false)]
    verify_account_scan: bool,
}

// `..` and symlinks survive lexical absolutisation, so two spellings of one file would compare unequal.
fn resolve_output(path: &str) -> anyhow::Result<PathBuf> {
    resolve_links(&std::path::absolute(path)?, 8)
}

fn resolve_links(path: &Path, hops: u8) -> anyhow::Result<PathBuf> {
    let (Some(parent), Some(file_name)) = (path.parent(), path.file_name()) else {
        anyhow::bail!("{} is not a path to a file", path.display());
    };
    // only the parent is canonicalised, so an output that does not exist yet still resolves.
    let parent = std::fs::canonicalize(parent)
        .with_context(|| format!("cannot resolve the directory of {}", path.display()))?;
    let resolved = parent.join(file_name);

    let Ok(target) = std::fs::read_link(&resolved) else {
        return Ok(resolved);
    };
    if hops == 0 {
        anyhow::bail!(
            "{} resolves through too many symbolic links",
            path.display()
        );
    }
    resolve_links(&parent.join(target), hops - 1)
}

impl Args {
    fn validate(&self) -> anyhow::Result<PathBuf> {
        let output_sqlite = resolve_output(&self.output_sqlite)?;
        let Some(output_slot) = self.output_slot.as_deref() else {
            return Ok(output_sqlite);
        };
        let output_slot = resolve_output(output_slot)?;

        if output_slot == output_sqlite {
            anyhow::bail!(
                "--output-slot and --output-sqlite both resolve to {}, promoting the DB renames it over the slot file and the slot value is lost",
                output_sqlite.display()
            );
        }
        if output_slot == temp_db_path(&output_sqlite) {
            anyhow::bail!(
                "--output-slot resolves to {}, the temporary file of --output-sqlite, which the DB run deletes before writing it",
                output_slot.display()
            );
        }

        Ok(output_sqlite)
    }
}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let mut builder = Builder::from_env(Env::default().default_filter_or("info"));
    builder.filter_module("solana_metrics::metrics", LevelFilter::Error);
    builder.init();
    let args: Args = Args::parse();
    let output_sqlite = args.validate()?;

    let now = SystemTime::now();
    let since_the_epoch = now.duration_since(UNIX_EPOCH)?;
    let current_timestamp = since_the_epoch.as_secs() as i64;

    info!(
        "Starting snapshot parser for tokens at timestamp {}",
        current_timestamp
    );

    info!("Loading filters from: {:?}", &args.filters);
    let filters = Filters::load(&args.filters)?;

    // let solana_ledger::genesis_utils::GenesisConfigInfo { genesis_config, .. } =
    //     solana_ledger::genesis_utils::create_genesis_config(100);
    // let bank: Arc<solana_runtime::bank::Bank> = Arc::new(solana_runtime::bank::Bank::new_for_tests(&genesis_config));
    info!("Creating bank from ledger path: {:?}", &args.ledger_path);
    let bank = create_bank_from_ledger(&args.ledger_path)?;
    assert!(bank.is_frozen());
    info!(
        "Bank created. Epoch: {}, slot: {}, hash: {}, timestamp from genesis: {}",
        bank.epoch(),
        bank.slot(),
        bank.hash(),
        bank.unix_timestamp_from_genesis()
    );

    // agave picks which archives to combine, so the loaded slot is not derivable from a file name
    if let Some(output_slot) = &args.output_slot {
        std::fs::write(output_slot, format!("{}\n", bank.slot()))
            .map_err(|e| anyhow::anyhow!("Failed to write bank slot to {output_slot}: {e}"))?;
        info!("Bank slot {} written to {}", bank.slot(), output_slot);
    }

    info!("Scanning accounts from the bank in a single pass over the storages...");
    let scanned_accounts = scan_required_accounts(&bank, &filters, args.verify_account_scan)?;

    info!("Creating progress bar instance...");
    let stats = Stats::new();
    let multi_progress = MultiProgress::new();
    let db_progress_counter = define_counter("db_execute", &multi_progress, &stats).await;
    let token_counter = define_counter(TOKEN_ACCOUNT_TABLE, &multi_progress, &stats).await;
    let vemnde_counter = define_counter(VE_MNDE_ACCOUNT_TABLE, &multi_progress, &stats).await;
    let native_stake_counter =
        define_counter(NATIVE_STAKE_ACCOUNT_TABLE, &multi_progress, &stats).await;

    let channel_size = args.channel_size.unwrap_or(1000);
    info!("Creating communication channels size {}...", channel_size);
    let (sender, receiver) = mpsc::channel(channel_size);

    let (consumer_ready_tx, consumer_ready_rx) = oneshot::channel();
    let db_handle: tokio::task::JoinHandle<anyhow::Result<()>> = {
        tokio::spawn(async move {
            info!("Starting SQLite executor task...");
            consumer_ready_tx
                .send(())
                .expect("Failed to send ready signal");
            let db = snapshot_parser_tokens_cli::db_connection::SQLiteExecutor::new(
                output_sqlite,
                args.sqlite_cache_size,
                args.sqlite_mmap_size,
                args.sqlite_tx_bulk,
                db_progress_counter,
                receiver,
            )?;
            db.start().await;
            debug!("SQLite executor task finished");
            Ok(())
        })
    };
    consumer_ready_rx
        .await
        .expect("Failed to receive SQLite ready signal");

    let token_handle = spawn_processor_task(
        ProcessorToken::new(
            scanned_accounts.token,
            sender.clone(),
            token_counter.clone(),
        )
        .await?,
    )
    .await?;

    let mint_handle = spawn_processor_task(
        ProcessorMint::new(bank.clone(), sender.clone(), &filters, token_counter).await?,
    )
    .await?;

    let vemnde_handle = spawn_processor_task(
        ProcessorVeMnde::new(
            scanned_accounts.voter,
            sender.clone(),
            &filters,
            vemnde_counter,
            current_timestamp,
        )
        .await?,
    )
    .await?;

    let native_stake_handle = spawn_processor_task(
        ProcessorNativeStake::new(
            bank.clone(),
            scanned_accounts.stake,
            sender.clone(),
            native_stake_counter,
        )
        .await?,
    )
    .await?;

    join_processor_tasks([
        token_handle,
        mint_handle,
        vemnde_handle,
        native_stake_handle,
    ])
    .await?;

    let (response_tx, response_rx) = oneshot::channel();
    sender
        .send(DbMessage::Shutdown {
            response: response_tx,
        })
        .await?;
    response_rx.await??;
    drop(sender);
    db_handle.await??;
    let _ = multi_progress;

    stats.print_info().await;

    info!("Finished.");
    log::logger().flush();

    std::process::exit(0);
}

async fn define_counter(
    name: &str,
    multi_progress: &MultiProgress,
    stats: &Stats,
) -> Arc<ProgressCounter> {
    let progress_counter = Arc::new(ProgressCounter::new(multi_progress, name));
    stats.add_callback(progress_counter.clone()).await;
    progress_counter
}

#[cfg(test)]
mod tests {
    use super::*;

    // Built directly: clap would read the `env` fallbacks and an ambient OUTPUT_SLOT
    // would silently replace the no-slot case.
    fn args_of(output_sqlite: &str, output_slot: Option<&str>) -> Args {
        Args {
            ledger_path: PathBuf::from("."),
            output_sqlite: output_sqlite.to_owned(),
            output_slot: output_slot.map(str::to_owned),
            filters: PathBuf::from("."),
            channel_size: None,
            sqlite_cache_size: None,
            sqlite_mmap_size: None,
            sqlite_tx_bulk: None,
            verify_account_scan: false,
        }
    }

    #[test]
    fn one_path_for_the_slot_and_the_db_is_rejected() {
        let err = args_of("./snapshot.db", Some("./snapshot.db"))
            .validate()
            .expect_err("promoting the DB over the slot file must not be a silent overwrite");
        assert!(
            err.to_string().contains("--output-slot"),
            "the error must name the colliding flag: {err}"
        );
    }

    #[test]
    fn another_spelling_of_the_db_path_is_rejected_for_the_slot() {
        args_of("./snapshot.db", Some("snapshot.db"))
            .validate()
            .expect_err("a relative alias of the DB path is the same file");

        let absolute = std::path::absolute("./snapshot.db").unwrap();
        args_of("./snapshot.db", Some(absolute.to_str().unwrap()))
            .validate()
            .expect_err("an absolute alias of the DB path is the same file");

        args_of("./snapshot.db", Some("./src/../snapshot.db"))
            .validate()
            .expect_err("a parent-component alias of the DB path is the same file");
    }

    #[test]
    fn the_temporary_file_of_the_db_is_rejected_for_the_slot() {
        args_of("./snapshot.db", Some("./_snapshot.db.tmp"))
            .validate()
            .expect_err("the DB run unlinks its temporary file before writing it");
    }

    #[test]
    fn distinct_output_paths_are_allowed() {
        args_of("./snapshot.db", Some("./slot.txt"))
            .validate()
            .unwrap();
        args_of("./snapshot.db", None).validate().unwrap();
    }
}
